def patch_of(*added, removed=()):
    """Build a hunk-only patch (GitHub API shape)."""
    body = ["-" + r for r in removed] + ["+" + a for a in added]
    return "@@ -1,%d +1,%d @@\n" % (len(removed), len(added)) + "\n".join(body)


def f(path, added=(), removed=(), status="modified", extra_add=0, extra_del=0):
    return {
        "filename": path,
        "status": status,
        "additions": len(added) + extra_add,
        "deletions": len(removed) + extra_del,
        "patch": patch_of(*added, removed=removed) if (added or removed) else None,
    }


def pr(title="Improve things", body="This PR improves things in a careful way.", assoc="MEMBER", login="alice"):
    return {"title": title, "body": body, "author_association": assoc, "user": {"login": login, "type": "User"}, "html_url": "https://github.com/o/r/pull/1", "number": 1, "base": {"ref": "main"}, "head": {"ref": "feat"}}


def score(files, meta=None, config=None):
    return pr_risk.score_pr({"pr": meta or pr(), "files": files}, config)


def rules(result):
    return {x["rule"] for x in result["findings"]}


