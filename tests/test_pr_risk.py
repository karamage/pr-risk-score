class TestHelpers(unittest.TestCase):
    def test_glob(self):
        g = pr_risk.glob_to_regex
        self.assertTrue(g("src/**/*.py").match("src/a/b/c.py"))
        self.assertTrue(g("src/**/*.py").match("src/c.py"))
        self.assertFalse(g("src/*.py").match("src/a/c.py"))
        self.assertTrue(g("*.lock").match("deep/dir/x.lock"))
        self.assertTrue(g("infra/").match("infra/a/b.tf"))

    def test_parse_target(self):
        t = pr_risk.parse_target("https://github.com/cli/cli/pull/123/files")
        self.assertEqual((t["owner"], t["repo"], t["number"]), ("cli", "cli", 123))
        t = pr_risk.parse_target("octo-org/my.repo#7")
        self.assertEqual((t["owner"], t["repo"], t["number"]), ("octo-org", "my.repo", 7))
        t = pr_risk.parse_target("https://ghe.example.com/a/b/pull/9")
        self.assertEqual(t["host"], "ghe.example.com")

    def test_added_lines_handles_sql_comment_removal(self):
        patch = "@@ -1,2 +1,2 @@\n--- old sql comment\n+-- new sql comment\n context"
        self.assertEqual(pr_risk.added_lines(patch), [(1, "-- new sql comment")])

    def test_parse_unified_diff(self):
        diff = (
            "diff --git a/a.py b/a.py\nnew file mode 100644\n--- /dev/null\n+++ b/a.py\n@@ -0,0 +1,2 @@\n+x = 1\n+eval(y)\n"
            "diff --git a/old.txt b/new.txt\nsimilarity index 100%\nrename from old.txt\nrename to new.txt\n"
        )
        files = pr_risk.parse_unified_diff(diff)
        self.assertEqual(files[0]["status"], "added")
        self.assertEqual(files[0]["additions"], 2)
        self.assertEqual(pr_risk.added_lines(files[0]["patch"])[1], (2, "eval(y)"))
        self.assertEqual(files[1]["status"], "renamed")

    def test_show_lines_numbers(self):
        out = pr_risk.render_numbered([f("a.py", added=["x = 1", "y = 2"])], [])
        self.assertIn("    2 + y = 2", out)

    def test_markdown_render(self):
        md = pr_risk.render_markdown(score([f("src/auth/a.py", added=["eval(x)"])]))
        self.assertIn(pr_risk.COMMENT_MARKER, md)
        self.assertIn("PR Risk Score", md)
        self.assertIn("src/auth/a.py:1", md)


class TestSemantic(unittest.TestCase):
    def base(self, files=None, **kw):
        return score(files or [f("src/auth/a.py", added=["x"] * 60)], **kw)

    def item(self, pts, esc=False, file_="src/auth/a.py"):
        return {"points": pts, "file": file_, "line": "3", "reason": "because", "escalation": esc}

    def test_adjustment_clamped_to_20(self):
        b = self.base()
        r = pr_risk.apply_semantic(b, {"items": [self.item(15), self.item(15), self.item(15)]})
        self.assertEqual(r["score"], min(100, b["score"] + 20))

    def test_single_item_clamped(self):
        b = self.base()
        r = pr_risk.apply_semantic(b, {"items": [self.item(-100)]})
        self.assertEqual(r["semantic"]["adjustment"], -15)

    def test_floor_cannot_be_lowered(self):
        b = score([f("migrations/1.sql", added=["DROP TABLE users;"])])
        r = pr_risk.apply_semantic(b, {"items": [self.item(-15), self.item(-15)]})
        self.assertGreaterEqual(r["score"], 75)
        self.assertTrue(r["needs_human_review"])

    def test_escalation_forces_human(self):
        b = self.base()
        r = pr_risk.apply_semantic(b, {"items": [self.item(5, esc=True)]})
        self.assertGreaterEqual(r["score"], 60)
        self.assertTrue(r["needs_human_review"])

    def test_negative_item_cannot_escalate(self):
        b = score([f("README.md", added=["x"])])
        r = pr_risk.apply_semantic(b, {"items": [self.item(-5, esc=True)]})
        self.assertFalse(r["semantic"]["escalated"])

    def test_uncited_items_ignored(self):
        b = self.base()
        r = pr_risk.apply_semantic(b, {"items": [{"points": -15, "reason": "trust me"}]})
        self.assertEqual(r["semantic"]["adjustment"], 0)

    def test_near_threshold_raised(self):
        b = self.base()
        need = 48 - b["score"]
        r = pr_risk.apply_semantic(b, {"items": [self.item(need)]})
        self.assertEqual(r["score"], 50)
        self.assertEqual(r["level"], "HIGH")

    def test_no_semantic_decrease(self):
        b = self.base()
        r = pr_risk.apply_semantic(b, {"items": [self.item(-10)]}, allow_decrease=False)
        self.assertEqual(r["score"], b["score"])

    def test_force_human_survives_semantic(self):
        b = score([f("infra/prod/x.yaml", added=["a: 1"])], config={"always_human_review_paths": ["infra/prod/**"]})
        r = pr_risk.apply_semantic(b, {"items": [self.item(-15)]})
        self.assertTrue(r["needs_human_review"])

    def test_garbage_rejected(self):
        with self.assertRaises(ValueError):
            pr_risk.apply_semantic(self.base(), ["not", "an", "object"])


class TestSecurityHardening(unittest.TestCase):
    def test_md_safe_neutralizes_mentions_links_html(self):
        out = pr_risk.md_safe("ping @my-org/admins [click](https://evil.example) <img src=x> <!-- pr-risk-score -->")
        self.assertNotIn("@my-org", out)
        self.assertNotIn("](https://", out)
        self.assertNotIn("<img", out)
        self.assertNotIn(pr_risk.COMMENT_MARKER, out)

    def test_title_cannot_spoof_marker_or_mention(self):
        meta = pr(title="fix <!-- pr-risk-score --> cc @everyone [x](https://evil.example)")
        md = pr_risk.render_markdown(score([f("src/a.py", added=["x"])], meta=meta))
        self.assertEqual(md.count(pr_risk.COMMENT_MARKER), 1)
        self.assertNotIn("@everyone", md)
        self.assertNotIn("](https://evil", md)

    def test_semantic_text_is_sanitized(self):
        b = score([f("src/a.py", added=["x"])])
        r = pr_risk.apply_semantic(b, {"items": [{"points": 1, "file": "a`b", "line": "1", "reason": "see [here](https://evil.example) @team"}], "summary": "<script>x</script>"})
        md = pr_risk.render_markdown(r)
        self.assertNotIn("<script>", md)
        self.assertNotIn("@team", md)
        self.assertNotIn("](https://evil", md)

    def test_backtick_in_filename_cannot_break_code_span(self):
        md = pr_risk.render_markdown(score([f("src/x`<img src=y>`.py", added=["eval(a)"])]))
        self.assertNotIn("x`<img", md)               # backtick neutralized...
        self.assertIn("`src/x'<img src=y>'.py", md)  # ...so the HTML stays inside a code span (rendered as text)

    def test_safe_repo_path(self):
        self.assertEqual(pr_risk.safe_repo_path("a b/c#d.go"), "a%20b/c%23d.go")
        self.assertEqual(pr_risk.safe_repo_path("x?ref=main"), "x%3Fref%3Dmain")
        for bad in ["../../user", "a/../b", "/abs", "a//b", "a\nb", ""]:
            self.assertIsNone(pr_risk.safe_repo_path(bad), bad)

    def test_base_option_injection_rejected(self):
        with self.assertRaises(pr_risk.CollectError):
            pr_risk.collect_local("--output=/tmp/x")

    def test_regexes_are_linear_enough(self):
        import time
        evil = [".execute('" + "select " * 140, "'" * 1000, "catch (" * 140, "password = '" + "a" * 990, "ignore the previous " * 50]
        for rule in pr_risk.RULES:
            for line in evil:
                t0 = time.perf_counter()
                rule["_re"].search(line)
                self.assertLess(time.perf_counter() - t0, 0.05, rule["id"])

    def test_scan_budget(self):
        old = pr_risk.MAX_SCANNED_LINES
        pr_risk.MAX_SCANNED_LINES = 10
        try:
            r = score([f("src/a.py", added=["x"] * 20 + ["eval(y)"])])
            self.assertTrue(r["stats"]["scan_truncated"])
            self.assertNotIn("dynamic-eval", rules(r))
        finally:
            pr_risk.MAX_SCANNED_LINES = old


