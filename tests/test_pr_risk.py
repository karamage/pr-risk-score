class TestCLI(unittest.TestCase):
    def _run(self, *args):
        return subprocess.run([sys.executable, SCRIPT] + list(args), stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)

    def test_cli_input_json_and_fail_above(self):
        data = {"pr": pr(), "files": [f("migrations/1.sql", added=["DROP TABLE x;"])]}
        with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as fh:
            json.dump(data, fh)
        try:
            out = self._run("--input", fh.name, "--json")
            self.assertEqual(out.returncode, 0, out.stderr)
            self.assertGreaterEqual(json.loads(out.stdout)["score"], 75)
            self.assertEqual(self._run("--input", fh.name, "--fail-above", "50").returncode, 3)
        finally:
            os.unlink(fh.name)

    def test_cli_render_with_semantic(self):
        base = score([f("src/auth/a.py", added=["x"] * 60)])
        sem = {"items": [{"points": 5, "file": "src/auth/a.py", "line": "3", "reason": "r", "escalation": True}]}
        paths = []
        for obj in (base, sem):
            with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as fh:
                json.dump(obj, fh)
                paths.append(fh.name)
        try:
            out = self._run("--render", paths[0], "--semantic", paths[1], "--json")
            self.assertEqual(out.returncode, 0, out.stderr)
            self.assertTrue(json.loads(out.stdout)["needs_human_review"])
            md = self._run("--render", paths[0], "--semantic", paths[1])
            self.assertIn("escalation", md.stdout)
        finally:
            for p_ in paths:
                os.unlink(p_)

    def test_cli_bad_target(self):
        out = self._run("not a pr")
        self.assertEqual(out.returncode, 2)
        self.assertIn("unrecognized", out.stderr)


