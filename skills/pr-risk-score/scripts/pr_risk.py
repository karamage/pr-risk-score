#!/usr/bin/env python3
"""
pr-risk-score — deterministic, explainable risk scoring for pull requests.

Scores a GitHub PR (or your local branch) from 0 to 100 and decides whether a
human must review it. Every point is traceable to a factor, a file, or a line.

Requirements: Python 3.8+ (stdlib only). Remote PRs additionally need the
GitHub CLI (`gh`) authenticated with read access to the repository.

Usage:
  pr_risk.py https://github.com/OWNER/REPO/pull/123
  pr_risk.py OWNER/REPO#123
  pr_risk.py 123                      # PR in the current repo (via gh)
  pr_risk.py --local --base main      # your branch vs. main, before opening a PR
  pr_risk.py --input pr.json          # offline: {"pr": {...}, "files": [...]}

Options:
  --format md|json     output format (default: md)
  --config PATH        .pr-risk.json to use (default: read from the PR's BASE branch)
  --threshold N        human-review threshold (default: 50, or config)
  --fail-above N       exit with code 3 when score >= N (for CI gates)
  --github-output      append score/level/needs_human_review to $GITHUB_OUTPUT
  --save-raw PATH      save fetched PR data; reuse with --input PATH (no refetch)
  --show-lines [GLOB]  print the diff with new-file line numbers (for exact file:line citations)
  --render FILE        re-render a saved --json result (add --semantic FILE to apply a review)
  --list-rules         print built-in categories and rules
"""
