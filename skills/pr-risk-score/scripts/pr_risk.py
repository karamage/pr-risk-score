class CollectError(RuntimeError):
    pass


def run(cmd: List[str], check: bool = True) -> str:
    try:
        res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
    except FileNotFoundError:
        raise CollectError("command not found: %s" % cmd[0])
    if check and res.returncode != 0:
        raise CollectError("%s failed: %s" % (" ".join(cmd[:3]), res.stderr.strip() or res.stdout.strip()))
    return res.stdout


PR_URL_RE = re.compile(r"^(?:https?://)?(?P<host>[^/\s]+)/(?P<owner>[^/\s]+)/(?P<repo>[^/\s]+)/pull/(?P<num>\d+)")
PR_SHORT_RE = re.compile(r"^(?P<owner>[\w.-]+)/(?P<repo>[\w.-]+)#(?P<num>\d+)$")


def parse_target(target: str) -> Dict[str, Any]:
    t = target.strip()
    m = PR_URL_RE.match(t)
    if m:
        return {"host": m.group("host"), "owner": m.group("owner"), "repo": m.group("repo"), "number": int(m.group("num"))}
    m = PR_SHORT_RE.match(t)
    if m:
        return {"host": "github.com", "owner": m.group("owner"), "repo": m.group("repo"), "number": int(m.group("num"))}
    if re.fullmatch(r"#?\d+", t):
        nwo = run(["gh", "repo", "view", "--json", "nameWithOwner", "-q", ".nameWithOwner"]).strip()
        owner, repo = nwo.split("/", 1)
        return {"host": "github.com", "owner": owner, "repo": repo, "number": int(t.lstrip("#"))}
    raise CollectError("unrecognized PR reference: %r (use a URL, OWNER/REPO#N, or N)" % target)


