def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(prog="pr_risk.py", description="Deterministic, explainable risk score (0-100) for a pull request.")
    ap.add_argument("target", nargs="?", help="PR URL, OWNER/REPO#N, or N (current repo)")
    ap.add_argument("--local", action="store_true", help="score the current git branch against --base")
    ap.add_argument("--base", default="origin/main", help="base ref for --local (default: origin/main)")
    ap.add_argument("--input", help="offline JSON file: {\"pr\": {...}, \"files\": [...]}")
    ap.add_argument("--config", help="path to .pr-risk.json (default: read from the PR's base branch)")
    ap.add_argument("--threshold", type=int, help="human-review threshold (overrides config)")
    ap.add_argument("--format", choices=["md", "json"], default="md")
    ap.add_argument("--json", action="store_true", help="shorthand for --format json")
    ap.add_argument("--fail-above", type=int, help="exit 3 when score >= N")
    ap.add_argument("--github-output", action="store_true", help="write outputs to $GITHUB_OUTPUT")
    ap.add_argument("--save-raw", metavar="PATH", help="also save the fetched PR data, reusable later with --input (avoids refetching)")
    ap.add_argument("--show-lines", nargs="*", metavar="GLOB", help="print the diff with new-file line numbers (optionally only files matching GLOBs) and exit")
    ap.add_argument("--render", metavar="RESULT_JSON", help="re-render a saved --json result (no network); combine with --semantic")
    ap.add_argument("--semantic", metavar="SEMANTIC_JSON", help="with --render: apply a semantic review {items:[{points,file,line,reason,escalation}],summary,focus,skip}")
    ap.add_argument("--no-semantic-decrease", action="store_true", help="with --semantic: ignore downward adjustments (recommended in CI)")
    ap.add_argument("--list-rules", action="store_true", help="print the built-in categories and pattern rules as markdown")
    ap.add_argument("--version", action="version", version="pr-risk-score " + VERSION)
    a = ap.parse_args(argv)

    if a.list_rules:
        print(render_rules())
        return 0
    if a.render:
        try:
            with open(a.render, encoding="utf-8") as fh:
                result = json.load(fh)
            if a.semantic:
                with open(a.semantic, encoding="utf-8") as fh:
                    result = apply_semantic(result, json.load(fh), allow_decrease=not a.no_semantic_decrease)
        except (OSError, ValueError) as e:
            print("pr-risk-score: %s" % e, file=sys.stderr)
            return 2
        return emit(result, a)

    try:
        config: Optional[Dict[str, Any]] = None
        if a.config:
            with open(a.config, encoding="utf-8") as fh:
                config = json.load(fh)
        if a.input:
            with open(a.input, encoding="utf-8") as fh:
                data = json.load(fh)
        elif a.local:
            data = collect_local(a.base)
            if config is None:
                config = load_local_config(data["pr"]["base"]["sha"])
        elif a.target:
            ref = parse_target(a.target)
            data = collect_remote(ref)
            if config is None:
                config = load_remote_config(ref, ((data["pr"].get("base") or {}).get("sha")) or "")
        else:
            ap.error("give a PR reference, --local, or --input")
            return 2
    except CollectError as e:
        print("pr-risk-score: %s" % e, file=sys.stderr)
        return 2

    if a.save_raw:
        with open(a.save_raw, "w", encoding="utf-8") as fh:
            json.dump(data, fh)

    if a.show_lines is not None:
        print(render_numbered(data.get("files") or [], a.show_lines))
        return 0

    config = dict(config or {})
    if a.threshold is not None:
        config["human_review_threshold"] = a.threshold
    result = score_pr(data, config)
    return emit(result, a)


def emit(result: Dict[str, Any], a: argparse.Namespace) -> int:
    if a.json or a.format == "json":
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        print(render_markdown(result))

    if a.github_output and os.environ.get("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as fh:
            fh.write("score=%d\nlevel=%s\nneeds_human_review=%s\n" % (result["score"], result["level"], str(result["needs_human_review"]).lower()))

    if a.fail_above is not None and result["score"] >= a.fail_above:
        return 3
    return 0


if __name__ == "__main__":
    sys.exit(main())
