FACTOR_MAX = {"size": 20, "spread": 10, "sensitive": 40, "patterns": 30, "tests": 20, "shape": 10, "context": 10}
FACTOR_LABEL = {
    "size": "Change size",
    "spread": "Change spread",
    "sensitive": "Sensitive areas",
    "patterns": "Risky code patterns",
    "tests": "Test coverage gap",
    "shape": "Change shape",
    "context": "Author & context",
}


def score_pr(data: Dict[str, Any], config: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    config = config or {}
    pr = data.get("pr") or {}
    raw_files = data.get("files") or []
    disabled = set(config.get("disable_rules", []))
    rule_ignore: Dict[str, List[str]] = config.get("rule_ignore_paths", {})
    ignore_globs = list(config.get("ignore_paths", []))
    always_human_globs = list(config.get("always_human_review_paths", []))
    threshold = int(config.get("human_review_threshold", DEFAULT_THRESHOLD))
    cat_points_override = config.get("category_points", {})
    custom_sensitive = config.get("sensitive_paths", [])
    custom_compiled = [(c["name"], int(c.get("points", 10)), [glob_to_regex(p) for p in c.get("patterns", [])], c.get("label", c["name"])) for c in custom_sensitive]

    files = []
    for f in raw_files:
        path = re.sub(r"[`\x00-\x1f]", "'", f.get("filename") or f.get("path") or "")
        cls = classify(path)
        files.append(
            {
                "path": path,
                "status": f.get("status", "modified"),
                "additions": int(f.get("additions", 0) or 0),
                "deletions": int(f.get("deletions", 0) or 0),
                "patch": f.get("patch"),
                "binary": bool(f.get("binary")) or (f.get("patch") is None and f.get("status") not in ("removed", "renamed") and not f.get("additions") and not f.get("deletions")),
                "previous": f.get("previous_filename"),
                "head_text": (f.get("head_text") or "")[:4000],
                "ignored": match_any(path, ignore_globs),
                **cls,
            }
        )

    for fc in files:
        if not fc["generated"] and (fc["patch"] or fc["head_text"]):
            head = fc["head_text"] or " ".join(t for _ln, t in added_lines(fc["patch"])[:12])
            if GENERATED_HEADER_RE.search(head):
                fc["generated"] = True
                fc["code"] = False
    effective = [f for f in files if not (f["ignored"] or f["lockfile"] or f["generated"])]
    # Prose is cheaper to get wrong than code: documentation lines count 1/5 toward size.
    eff_lines = int(round(sum((f["additions"] + f["deletions"]) * (0.2 if f["doc"] else 1.0) for f in effective)))
    total_add = sum(f["additions"] for f in files)
    total_del = sum(f["deletions"] for f in files)

    factors: Dict[str, Dict[str, Any]] = {k: {"points": 0, "reasons": []} for k in FACTOR_MAX}
    file_risk: Dict[str, Dict[str, Any]] = {}

    def bump_file(path: str, pts: float, why: str) -> None:
        fr = file_risk.setdefault(path, {"path": path, "points": 0, "reasons": []})
        fr["points"] += pts
        if why not in fr["reasons"]:
            fr["reasons"].append(why)

    # 1. Size -------------------------------------------------------------------------
    size_pts = step(eff_lines, [(10, 0), (50, 3), (150, 6), (300, 10), (600, 14), (1000, 17), (float("inf"), 20)])
    factors["size"]["points"] = size_pts
    excluded = len(files) - len(effective)
    factors["size"]["reasons"].append(
        "%d effective lines changed%s" % (eff_lines, " (%d lockfile/generated/ignored files excluded)" % excluded if excluded else "")
    )

    # 2. Spread -----------------------------------------------------------------------
    n_files = len(effective)
    top_dirs = {f["path"].split("/")[0] if "/" in f["path"] else "." for f in effective}
    spread_pts = step(n_files, [(3, 0), (10, 2), (20, 4), (40, 6), (float("inf"), 8)])
    if len(top_dirs) >= 4:
        spread_pts += 2
    factors["spread"]["points"] = min(spread_pts, FACTOR_MAX["spread"])
    factors["spread"]["reasons"].append("%d files across %d top-level directories" % (n_files, len(top_dirs)))

    # 3. Sensitive areas ---------------------------------------------------------------
    hit_cats: Dict[str, List[str]] = {}
    cat_meta: Dict[str, Tuple[int, str]] = {}
    for name, (pts, _rx, label) in SENSITIVE_CATEGORIES.items():
        cat_meta[name] = (int(cat_points_override.get(name, pts)), label)
    for name, pts, _globs, label in custom_compiled:
        cat_meta[name] = (pts, label)
    for f in files:
        if f["ignored"]:
            continue
        lower = f["path"].lower()
        for name, rx in _SENSITIVE_COMPILED.items():
            if f["doc"] and name != "governance":
                continue  # docs are never sensitive, except files that steer reviewers or agents
            if f["test"] and name not in ("infrastructure", "governance"):
                continue  # tests *about* auth are not auth changes
            if rx.search(lower):
                hit_cats.setdefault(name, []).append(f["path"])
        for name, _pts, globs, _label in custom_compiled:
            if any(g.match(f["path"]) for g in globs):
                hit_cats.setdefault(name, []).append(f["path"])
    # lockfile-only dependency change counts as a lighter "dependencies" hit
    lockfiles = [f["path"] for f in files if f["lockfile"] and not f["ignored"]]
    lock_only = bool(lockfiles) and "dependencies" not in hit_cats
    sens_total = 0
    for name, paths in sorted(hit_cats.items(), key=lambda kv: -cat_meta[kv[0]][0]):
        pts, label = cat_meta[name]
        if pts <= 0:
            continue
        sens_total += pts
        factors["sensitive"]["reasons"].append("%s (+%d): %s" % (label, pts, ", ".join("`%s`" % p for p in paths[:3]) + (" …" if len(paths) > 3 else "")))
        for p in paths:
            bump_file(p, pts, label)
    if lock_only:
        sens_total += 3
        factors["sensitive"]["reasons"].append("lockfile-only dependency update (+3): %s" % ", ".join("`%s`" % p for p in lockfiles[:3]))
    factors["sensitive"]["points"] = min(sens_total, FACTOR_MAX["sensitive"])

    # 4. Risky code patterns -----------------------------------------------------------
    findings: List[Dict[str, Any]] = []
    fired: Dict[str, Dict[str, Any]] = {}
    scanned = 0
    scan_truncated = False
    for f in files:
        if f["ignored"] or f["lockfile"]:
            continue
        lines = added_lines(f["patch"])
        if scanned + len(lines) > MAX_SCANNED_LINES:
            lines = lines[: max(0, MAX_SCANNED_LINES - scanned)]
            scan_truncated = True
        scanned += len(lines)
        if not lines:
            continue
        for rule in RULES:
            if rule["id"] in disabled:
                continue
            scope = rule["scope"]
            if scope == "code" and (f["test"] or f["doc"] or f["generated"]):
                continue
            if scope == "nondoc" and (f["test"] or f["doc"]):
                continue
            if rule_ignore.get(rule["id"]) and match_any(f["path"], rule_ignore[rule["id"]]):
                continue
            if scope == "workflow" and not f["workflow"]:
                continue
            if f["generated"] and scope != "all":
                continue
            for ln, text in lines:
                if len(text) > MAX_LINE_LEN:
                    continue  # minified / data blobs
                if rule["_re"].search(text):
                    snippet = redact(truncate(text)) if rule["id"].startswith("secret") or rule["id"] == "hardcoded-credential" else truncate(text)
                    findings.append({"rule": rule["id"], "severity": rule["sev"], "points": rule["pts"], "message": rule["msg"], "file": f["path"], "line": ln, "snippet": snippet})
                    entry = fired.setdefault(rule["id"], {"rule": rule, "count": 0})
                    entry["count"] += 1
                    bump_file(f["path"], rule["pts"], rule["msg"])
    # PR body can carry prompt injection too
    body = pr.get("body") or ""
    if "prompt-injection" not in disabled:
        inj = next(r for r in RULES if r["id"] == "prompt-injection")
        for i, text in enumerate(body.splitlines(), 1):
            if inj["_re"].search(text):
                findings.append({"rule": "prompt-injection", "severity": "high", "points": inj["pts"], "message": inj["msg"] + " in PR description", "file": "(PR description)", "line": i, "snippet": truncate(text)})
                fired.setdefault("prompt-injection", {"rule": inj, "count": 0})["count"] += 1
                break
    pat_total = 0
    for rid, entry in sorted(fired.items(), key=lambda kv: (SEV_ORDER[kv[1]["rule"]["sev"]], kv[0])):
        r = entry["rule"]
        pat_total += r["pts"]
        factors["patterns"]["reasons"].append("%s [%s] ×%d (+%d)" % (r["msg"], r["sev"], entry["count"], r["pts"]))
    factors["patterns"]["points"] = min(pat_total, FACTOR_MAX["patterns"])
    findings.sort(key=lambda x: (SEV_ORDER[x["severity"]], x["file"], x["line"]))

    # 5. Test coverage gap ----------------------------------------------------------
    code_lines = sum(f["additions"] + f["deletions"] for f in effective if f["code"])
    test_files = [f for f in files if f["test"] and not f["ignored"]]
    test_add = sum(f["additions"] for f in test_files)
    test_del = sum(f["deletions"] for f in test_files)
    test_lines = test_add + test_del
    t_pts = 0
    if code_lines >= 20 and test_lines == 0:
        t_pts = step(code_lines, [(99, 6), (299, 10), (float("inf"), 15)])
        factors["tests"]["reasons"].append("%d lines of code changed with no test changes" % code_lines)
    elif code_lines >= 100 and test_lines < code_lines * 0.1:
        t_pts = 5
        factors["tests"]["reasons"].append("test changes (%d lines) are <10%% of code changes (%d lines)" % (test_lines, code_lines))
    critical_cats = [c for c in ("security", "payments", "data_migration") if c in hit_cats]
    if t_pts and critical_cats:
        t_pts += 5
        factors["tests"]["reasons"].append("untested change touches %s (+5)" % "/".join(SENSITIVE_CATEGORIES[c][2].split(" /")[0] for c in critical_cats))
    removed_tests = [f["path"] for f in test_files if f["status"] == "removed"]
    if removed_tests or (test_del > 20 and test_del > test_add * 2):
        t_pts += 5
        factors["tests"]["reasons"].append("tests removed or net-shrunk (−%d/+%d lines%s)" % (test_del, test_add, "; deleted: " + ", ".join("`%s`" % p for p in removed_tests[:3]) if removed_tests else ""))
    if not factors["tests"]["reasons"]:
        factors["tests"]["reasons"].append("%d test lines for %d code lines" % (test_lines, code_lines) if code_lines else "no code changes")
    factors["tests"]["points"] = min(t_pts, FACTOR_MAX["tests"])

    # 6. Change shape --------------------------------------------------------------
    shape = 0
    deleted_src = [f["path"] for f in effective if f["status"] == "removed" and not f["test"] and not f["doc"]]
    if deleted_src:
        shape += min(2 * len(deleted_src), 6)
        factors["shape"]["reasons"].append("%d source files deleted" % len(deleted_src))
    binaries = [f["path"] for f in effective if f["binary"] and not f["doc"]]
    if binaries:
        shape += 2
        factors["shape"]["reasons"].append("binary files changed: %s" % ", ".join("`%s`" % p for p in binaries[:3]))
    big = [f for f in effective if f["additions"] + f["deletions"] > 500]
    if big:
        shape += 3
        factors["shape"]["reasons"].append("very large single-file change: %s" % ", ".join("`%s` (%d lines)" % (f["path"], f["additions"] + f["deletions"]) for f in big[:2]))
        for f in big:
            bump_file(f["path"], 3, "very large change")
    renames = [f for f in files if f["status"] == "renamed"]
    if len(renames) >= 5:
        shape += 2
        factors["shape"]["reasons"].append("%d files renamed/moved" % len(renames))
    if eff_lines >= 50 and total_del > 0 and total_add > 0 and min(total_add, total_del) / max(total_add, total_del) > 0.6 and eff_lines > 400:
        shape += 1
        factors["shape"]["reasons"].append("heavy rewrite (+%d/−%d)" % (total_add, total_del))
    factors["shape"]["points"] = min(shape, FACTOR_MAX["shape"])

    # 7. Author & context ----------------------------------------------------------
    ctx = 0
    assoc = (pr.get("author_association") or "").upper()
    user = (pr.get("user") or {}).get("login", "")
    is_bot = user.endswith("[bot]") or (pr.get("user") or {}).get("type") == "Bot"
    first_timer = assoc in FIRST_TIME_ASSOCIATIONS and not is_bot and not pr.get("local")
    if first_timer:
        ctx += 5
        factors["context"]["reasons"].append("author `%s` is a first-time / external contributor (%s)" % (user, assoc))
    title = pr.get("title") or ""
    if not pr.get("local") and len(body.strip()) < 20 and eff_lines > 50:
        ctx += 3
        factors["context"]["reasons"].append("PR description is empty or near-empty")
    if RUSHED_TITLE_RE.search(title):
        ctx += 3
        factors["context"]["reasons"].append("title suggests a rushed change (%r)" % RUSHED_TITLE_RE.search(title).group(0))
    if WIP_TITLE_RE.search(title) or pr.get("draft"):
        ctx += 2
        factors["context"]["reasons"].append("marked as draft / WIP")
    if is_bot:
        factors["context"]["reasons"].append("authored by bot `%s`" % user)
    if not factors["context"]["reasons"]:
        factors["context"]["reasons"].append("no contextual risk signals")
    factors["context"]["points"] = min(ctx, FACTOR_MAX["context"])

    # Aggregate, caps and floors ------------------------------------------------------
    raw = sum(v["points"] for v in factors.values())
    final = min(raw, 100)
    adjustments: List[Dict[str, Any]] = []
    has_secret = any(f["rule"].startswith("secret-") for f in findings)
    nonignored = [f for f in files if not f["ignored"]]

    if nonignored and all(f["doc"] for f in nonignored) and not has_secret and "prompt-injection" not in fired and "governance" not in hit_cats:
        if final > 10:
            adjustments.append({"type": "cap", "value": 10, "reason": "documentation-only change"})
            final = 10
    elif nonignored and all(f["doc"] or f["test"] for f in nonignored) and not has_secret and "governance" not in hit_cats:
        if final > 20:
            adjustments.append({"type": "cap", "value": 20, "reason": "tests/docs-only change"})
            final = 20

    floors: List[Tuple[int, str]] = []
    if has_secret:
        floors.append((90, "a secret/credential appears in the diff — rotate it, rewriting history is not enough"))
    destructive_in_migration = any(f["rule"] == "destructive-sql" and (_SENSITIVE_COMPILED["data_migration"].search(f["file"].lower())) for f in findings)
    if destructive_in_migration:
        floors.append((75, "destructive database migration (data loss is irreversible)"))
    if first_timer and any(f["workflow"] for f in nonignored):
        floors.append((75, "first-time contributor modifies CI workflows (supply-chain risk)"))
    if "workflow-pull-request-target" in fired:
        floors.append((60, "privileged workflow trigger added"))
    if "prompt-injection" in fired:
        floors.append((60, "content attempts to steer AI reviewers — never auto-approve"))
    if "governance" in hit_cats and any(p.lower().endswith(CONFIG_FILENAME) for p in hit_cats["governance"]):
        floors.append((50, "PR changes the risk-scoring configuration itself"))
    for value, reason in floors:
        if final < value:
            adjustments.append({"type": "floor", "value": value, "reason": reason})
            final = value

    forced_human: List[str] = []
    if always_human_globs:
        forced_human = [f["path"] for f in nonignored if match_any(f["path"], always_human_globs)]

    final = int(round(final))
    level, emoji = level_for(final)
    needs_human = final >= threshold or bool(forced_human)
    if forced_human:
        adjustments.append({"type": "force_human", "value": None, "reason": "touches always-human-review paths: %s" % ", ".join(forced_human[:3])})

    hotspots = sorted(file_risk.values(), key=lambda x: -x["points"])[:8]
    if len(hotspots) < 3:
        # No rule pointed anywhere: the semantic reviewer still needs a place to start.
        seen = {h["path"] for h in hotspots}
        biggest = sorted((f for f in effective if f["code"] and f["path"] not in seen), key=lambda f: -(f["additions"] + f["deletions"]))
        for f in biggest[: 3 - len(hotspots)]:
            hotspots.append({"path": f["path"], "points": 0, "reasons": ["largest code change (+%d/−%d); no rule fired, review for behavior" % (f["additions"], f["deletions"])]})
    sev_counts = {s: sum(1 for x in findings if x["severity"] == s) for s in SEV_ORDER}

    return {
        "tool": "pr-risk-score",
        "version": VERSION,
        "target": {
            "url": pr.get("html_url") or "",
            "number": pr.get("number"),
            "title": title,
            "author": user,
            "author_association": assoc,
            "base": (pr.get("base") or {}).get("ref"),
            "head": (pr.get("head") or {}).get("ref"),
            "local": bool(pr.get("local")),
            "state": "merged" if pr.get("merged_at") else (pr.get("state") or ("local" if pr.get("local") else "")),
            "head_sha": (pr.get("head") or {}).get("sha"),
        },
        "score": final,
        "raw_score": raw,
        "level": level,
        "emoji": emoji,
        "threshold": threshold,
        "needs_human_review": needs_human,
        "decision": "human_review_required" if needs_human else "ai_review_sufficient",
        "factors": [
            {"key": k, "label": FACTOR_LABEL[k], "points": factors[k]["points"], "max": FACTOR_MAX[k], "reasons": factors[k]["reasons"]} for k in FACTOR_MAX
        ],
        "adjustments": adjustments,
        "findings": findings[:50],
        "finding_counts": sev_counts,
        "hotspots": hotspots,
        "stats": {
            "files": len(files),
            "effective_files": n_files,
            "additions": total_add,
            "deletions": total_del,
            "effective_lines": eff_lines,
            "code_lines": code_lines,
            "test_lines": test_lines,
            "patch_missing": [f["path"] for f in files if f["patch"] is None and not f["binary"] and f["status"] != "removed"][:20],
            "scan_truncated": scan_truncated,
        },
    }


