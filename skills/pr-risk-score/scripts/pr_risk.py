def md_safe(text: Any) -> str:
    """Make untrusted text (PR titles, file names, snippets, model output) safe for a PR comment.
    Neutralizes @mentions and #refs everywhere; outside code spans, also escapes HTML and
    markdown links, so a crafted title can't ping teams or plant links in a bot comment."""
    s = str(text).replace("\r", " ").replace("\n", " ")
    s = re.sub(r"@(?=[A-Za-z0-9])", "@" + WORD_JOINER, s)
    parts = s.split("`")
    for i in range(0, len(parts), 2):  # even indexes are outside code spans
        seg = parts[i].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        seg = re.sub(r"([\[\]!])", r"\\\1", seg)
        seg = re.sub(r"(https?)://", r"\1:" + WORD_JOINER + "//", seg)
        parts[i] = seg
    if len(parts) % 2 == 0:  # unbalanced backtick: close the span rather than eat the rest
        parts[-1] += "`"
    return "`".join(parts).replace("|", "\\|")


def md_code(text: Any) -> str:
    """Untrusted text rendered inside a code span."""
    return "`%s`" % re.sub(r"@(?=[A-Za-z0-9])", "@" + WORD_JOINER, str(text).replace("`", "'").replace("\n", " "))


def bar(points: float, maximum: int, width: int = 10) -> str:
    filled = int(round(width * points / maximum)) if maximum else 0
    return "█" * filled + "░" * (width - filled)


SEMANTIC_ITEM_MAX = 15       # a single semantic item can't move the score more than this
SEMANTIC_TOTAL_MAX = 20      # the whole semantic layer is clamped to ±20
ESCALATION_FLOOR = 60


def apply_semantic(base: Dict[str, Any], sem: Dict[str, Any], allow_decrease: bool = True) -> Dict[str, Any]:
    """Combine the deterministic result with a semantic review, enforcing every bound in code.

    The model only proposes items; it never computes the score. This keeps the ±20 clamp,
    floors, escalation, and the near-threshold rule identical whether a human, Claude, or a
    prompt-injected Claude wrote the semantic JSON."""
    if not isinstance(sem, dict):
        raise ValueError("semantic review must be a JSON object")
    items_in = sem.get("items") or []
    if not isinstance(items_in, list):
        raise ValueError("semantic.items must be a list")
    items: List[Dict[str, Any]] = []
    for it in items_in[:20]:
        if not isinstance(it, dict):
            continue
        try:
            pts = int(it.get("points", 0))
        except (TypeError, ValueError):
            continue
        reason = truncate(str(it.get("reason") or ""), 300)
        file_ = truncate(str(it.get("file") or ""), 200)
        if not reason or not file_:
            continue  # uncited items don't count
        pts = max(-SEMANTIC_ITEM_MAX, min(SEMANTIC_ITEM_MAX, pts))
        items.append({"points": pts, "file": file_, "line": truncate(str(it.get("line") or ""), 20), "reason": reason, "escalation": bool(it.get("escalation")) and pts > 0})

    raw_adj = sum(i["points"] for i in items)
    adj = max(-SEMANTIC_TOTAL_MAX, min(SEMANTIC_TOTAL_MAX, raw_adj))
    notes: List[str] = []
    if adj != raw_adj:
        notes.append("semantic items summed to %+d, clamped to %+d" % (raw_adj, adj))
    if not allow_decrease and adj < 0:
        notes.append("downward semantic adjustment (%+d) ignored by policy" % adj)
        adj = 0

    floor = max([int(x["value"]) for x in base.get("adjustments", []) if x.get("type") == "floor"] or [0])
    baseline = int(base["score"])
    score = max(floor, min(100, baseline + adj))
    if baseline + adj < floor:
        notes.append("held at floor %d" % floor)
    escalated = [i for i in items if i["escalation"]]
    if escalated and score < ESCALATION_FLOOR:
        notes.append("escalated to %d: %s" % (ESCALATION_FLOOR, escalated[0]["reason"]))
        score = ESCALATION_FLOOR
    threshold = int(base.get("threshold", DEFAULT_THRESHOLD))
    if threshold - 3 <= score < threshold:
        notes.append("within 3 points of the threshold, raised to %d" % threshold)
        score = threshold
    forced = any(x.get("type") == "force_human" for x in base.get("adjustments", []))
    level, emoji = level_for(score)
    needs_human = score >= threshold or forced or bool(escalated)

    out = dict(base)
    out.update({
        "baseline_score": baseline,
        "score": score,
        "level": level,
        "emoji": emoji,
        "needs_human_review": needs_human,
        "decision": "human_review_required" if needs_human else "ai_review_sufficient",
        "semantic": {
            "adjustment": adj,
            "items": items,
            "escalated": bool(escalated),
            "notes": notes,
            "summary": truncate(str(sem.get("summary") or ""), 300),
            "focus": [truncate(str(x), 300) for x in (sem.get("focus") or [])[:6]],
            "skip": [truncate(str(x), 200) for x in (sem.get("skip") or [])[:6]],
        },
    })
    return out


def render_markdown(r: Dict[str, Any]) -> str:
    t = r["target"]
    sem = r.get("semantic")
    lines = [COMMENT_MARKER]
    lines.append("## %s PR Risk Score: **%d / 100** — %s" % (r["emoji"], r["score"], r["level"]))
    lines.append("")
    lines.append("`%s` %d" % (bar(r["score"], 100, 20), r["score"]))
    lines.append("")
    if r["needs_human_review"]:
        lines.append("**Decision:** 👀 **Human review required** (threshold %d)" % r["threshold"])
    else:
        lines.append("**Decision:** 🤖 AI review is sufficient (score < %d)" % r["threshold"])
    if sem and sem.get("summary"):
        lines.append("")
        lines.append(md_safe(sem["summary"]))
    lines.append("")
    ident = t["url"] or ("local branch %s vs %s" % (md_code(t["head"]), md_code(t["base"])))
    s = r["stats"]
    state = " · already merged (retrospective)" if t.get("state") == "merged" else ""
    lines.append("> %s%s%s  " % (ident, (" — " + md_safe(t["title"])) if t["title"] else "", state))
    lines.append("> +%d / −%d across %d files (%d effective lines)" % (s["additions"], s["deletions"], s["files"], s["effective_lines"]))
    if sem is not None:
        lines.append("")
        lines.append("| Layer | Points | Evidence |")
        lines.append("|---|---:|---|")
        top = sorted((f for f in r["factors"] if f["points"]), key=lambda f: -f["points"])[:3]
        lines.append("| Baseline (deterministic) | %d | %s |" % (r["baseline_score"], md_safe("; ".join("%s %d" % (f["label"], f["points"]) for f in top)) or "—"))
        lines.append("| Semantic adjustment | %+d | %d cited item(s) |" % (sem["adjustment"], len(sem["items"])))
        if sem["notes"]:
            lines.append("| Escalation / floors / policy | | %s |" % md_safe("; ".join(sem["notes"])))
        if sem["items"]:
            lines.append("")
            lines.append("**Semantic items**")
            for it in sem["items"]:
                loc = it["file"] + (":" + it["line"] if it["line"] else "")
                lines.append("- %+d — %s — %s%s" % (it["points"], md_code(loc), md_safe(it["reason"]), "  ⚠ **escalation**" if it["escalation"] else ""))
        if sem["focus"]:
            lines.append("")
            lines.append("**If a human reviews, focus on:**")
            lines.extend("- " + md_safe(x) for x in sem["focus"])
        if sem["skip"]:
            lines.append("")
            lines.append("**Safe to skip:** " + md_safe("; ".join(sem["skip"])))
        lines.append("")
        lines.append("<details><summary><b>Baseline breakdown</b></summary>")
    lines.append("")
    lines.append("| Factor | Score | | Why |")
    lines.append("|---|---:|---|---|")
    for f in r["factors"]:
        lines.append("| %s | %d/%d | `%s` | %s |" % (f["label"], f["points"], f["max"], bar(f["points"], f["max"]), "<br>".join(md_safe(x) for x in f["reasons"]) or "—"))
    if r["adjustments"]:
        lines.append("")
        lines.append("**Adjustments** (raw %d → %d)" % (r["raw_score"], r.get("baseline_score", r["score"])))
        for a in r["adjustments"]:
            label = {"cap": "capped at %s" % a["value"], "floor": "floor %s" % a["value"], "force_human": "human review forced"}[a["type"]]
            lines.append("- %s — %s" % (label, md_safe(a["reason"])))
    if r["findings"]:
        lines.append("")
        lines.append("<details><summary><b>Findings</b> (%d)</summary>" % len(r["findings"]))
        lines.append("")
        for x in r["findings"][:25]:
            lines.append("- **%s** %s — %s  \n  %s" % (x["severity"].upper(), md_code("%s:%s" % (x["file"], x["line"])), md_safe(x["message"]), md_code(x["snippet"])))
        lines.append("")
        lines.append("</details>")
    if r["hotspots"]:
        lines.append("")
        lines.append("**Review hotspots**, start here:")
        for h in r["hotspots"][:5]:
            lines.append("1. %s — %s" % (md_code(h["path"]), md_safe("; ".join(h["reasons"][:3]))))
    if r["stats"]["patch_missing"]:
        lines.append("")
        lines.append("_Note: GitHub omitted the diff for %d large file(s); pattern checks could not inspect them._" % len(r["stats"]["patch_missing"]))
    if r["stats"].get("scan_truncated"):
        lines.append("")
        lines.append("_Note: pattern scan stopped after %d added lines; the rest of this very large PR was not pattern-checked._" % MAX_SCANNED_LINES)
    if sem is not None:
        lines.append("")
        lines.append("</details>")
    lines.append("")
    layer = "deterministic baseline + semantic review" if sem is not None else "deterministic baseline"
    lines.append("<sub>Generated by [pr-risk-score](https://github.com/karamage/pr-risk-score) v%s · %s · scores are a triage signal, not a verdict</sub>" % (r["version"], layer))
    return "\n".join(lines)


def render_numbered(files: List[Dict[str, Any]], globs: List[str]) -> str:
    """Print patches with new-file line numbers so `file:line` citations are exact."""
    out: List[str] = []
    for f in files:
        path = f.get("filename") or ""
        if globs and not match_any(path, globs):
            continue
        out.append("=== %s (%s, +%s/-%s)" % (path, f.get("status"), f.get("additions"), f.get("deletions")))
        if not f.get("patch"):
            out.append("    (no patch: binary, removed, or too large for the API)")
            continue
        ln = 0
        for line in f["patch"].splitlines():
            m = HUNK_RE.match(line)
            if m:
                ln = int(m.group(1))
                out.append(line)
            elif line.startswith("+"):
                out.append("%5d + %s" % (ln, line[1:]))
                ln += 1
            elif line.startswith("-"):
                out.append("      - %s" % line[1:])
            elif line.startswith("\\"):
                continue
            else:
                out.append("%5d   %s" % (ln, line[1:] if line.startswith(" ") else line))
                ln += 1
    return "\n".join(out)


def render_rules() -> str:
    out = ["| Category | Points | Covers |", "|---|---:|---|"]
    for name, (pts, _rx, label) in SENSITIVE_CATEGORIES.items():
        out.append("| `%s` | %d | %s |" % (name, pts, label))
    out += ["", "| Rule id | Severity | Points | Scope | Detects |", "|---|---|---:|---|---|"]
    for r in sorted(RULES, key=lambda r: (SEV_ORDER[r["sev"]], r["id"])):
        out.append("| `%s` | %s | %d | %s | %s |" % (r["id"], r["sev"], r["pts"], r["scope"], r["msg"]))
    return "\n".join(out)


