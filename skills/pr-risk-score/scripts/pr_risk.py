def glob_to_regex(pattern: str) -> "re.Pattern[str]":
    """Gitignore-style glob -> regex. `**` crosses directories, `*` does not.
    A pattern without '/' matches at any depth (like .gitignore)."""
    p = pattern.strip()
    if p.startswith("./"):
        p = p[2:]
    anchored = "/" in p.rstrip("/")
    if p.startswith("/"):
        p = p[1:]
    out = []
    i = 0
    while i < len(p):
        c = p[i]
        if c == "*":
            if p[i : i + 3] == "**/":
                out.append("(?:.*/)?")
                i += 3
                continue
            if p[i : i + 2] == "**":
                out.append(".*")
                i += 2
                continue
            out.append("[^/]*")
        elif c == "?":
            out.append("[^/]")
        else:
            out.append(re.escape(c))
        i += 1
    body = "".join(out)
    if p.endswith("/"):
        body += ".*"
    prefix = "^" if anchored else "^(?:.*/)?"
    return re.compile(prefix + body + "(?:/.*)?$")


def match_any(path: str, patterns: Iterable[str]) -> bool:
    return any(glob_to_regex(p).match(path) for p in patterns)


HUNK_RE = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")


def added_lines(patch: Optional[str]) -> List[Tuple[int, str]]:
    """Return (new_line_number, text) for each added line of a hunk-only patch."""
    if not patch:
        return []
    out: List[Tuple[int, str]] = []
    ln = 0
    in_hunk = False
    for line in patch.splitlines():
        m = HUNK_RE.match(line)
        if m:
            ln = int(m.group(1))
            in_hunk = True
            continue
        if not in_hunk:
            continue
        if line.startswith("+"):
            out.append((ln, line[1:]))
            ln += 1
        elif line.startswith("-") or line.startswith("\\"):
            continue
        else:
            ln += 1
    return out


def removed_lines(patch: Optional[str]) -> List[str]:
    if not patch:
        return []
    out, in_hunk = [], False
    for line in patch.splitlines():
        if HUNK_RE.match(line):
            in_hunk = True
            continue
        if in_hunk and line.startswith("-"):
            out.append(line[1:])
    return out


def classify(path: str) -> Dict[str, bool]:
    lower = path.lower()
    is_lock = bool(LOCKFILE_RE.search(lower))
    is_gen = bool(GENERATED_RE.search(lower))
    is_test = bool(TEST_RE.search(path))
    is_doc = bool(DOC_RE.search(lower)) and not is_test
    is_code = bool(CODE_EXT_RE.search(lower)) and not (is_test or is_doc or is_gen)
    return {
        "lockfile": is_lock,
        "generated": is_gen,
        "test": is_test,
        "doc": is_doc,
        "code": is_code,
        "workflow": bool(WORKFLOW_RE.search(lower)),
    }


def level_for(score: int) -> Tuple[str, str]:
    for minimum, name, emoji in LEVELS:
        if score >= minimum:
            return name, emoji
    return "LOW", "🟢"


def step(value: float, table: List[Tuple[float, int]]) -> int:
    """table: ascending [(upper_bound, points)], returns points for first bound >= value."""
    for bound, pts in table:
        if value <= bound:
            return pts
    return table[-1][1]


def truncate(s: str, n: int = 100) -> str:
    s = s.strip()
    return s if len(s) <= n else s[: n - 1] + "…"


def redact(s: str) -> str:
    """Never echo a secret back into a PR comment."""
    return re.sub(r"([A-Za-z0-9_\-]{4})[A-Za-z0-9_\-/+=]{8,}", r"\1••••", s)


